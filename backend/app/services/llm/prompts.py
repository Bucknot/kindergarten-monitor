def build_reduce_prompt(
    child_name: str,
    focus_prompt: str,
    speakers_summary: str,
    block_summaries: List[Dict[str, Any]],
    acoustic_events: List[Dict[str, Any]],
    coverage_text: str,
    context_block: str = ""
) -> str:
    ctx_section = f"\n{context_block}\n" if context_block else ""
    blocks_text = "\n\n".join([
        f"### בלוק [{b.get('time_range', '')}] - {b.get('phase_name', '')}\n"
        f"סיכום: {b.get('summary', '')}\n"
        f"אירועי מצוקה ובכי: {', '.join(b.get('distress_events', [])) or 'ללא'}\n"
        f"התנהלות הצוות: {b.get('staff_conduct_notes', '')}\n"
        f"נורות אזהרה: {', '.join(b.get('potential_red_flags', [])) or 'אין'}"
        for b in block_summaries
    ])

    events_text = "\n".join([
        f"- [{e.get('start_formatted', '')}-{e.get('end_formatted', '')}] {e.get('event_type')}: {e.get('description', '')} (תגובת צוות: {e.get('adult_response') or 'לא תועדה'})"
        for e in acoustic_events
    ]) or "לא אותרו אירועים אקוסטיים חריגים."

    return f"""לפניך סיכומי שלבי היום ואירועי האקוסטיקה מתוך ההקלטה בגן:

- **הילד במוקד**: {child_name or 'הילד העונד את המקליט'}
- **שאלת מיקוד מההורה**: {focus_prompt or 'ניתוח כללי של היום והתנהגות הצוות'}
{ctx_section}
- **משתתפים**:
{speakers_summary}

{coverage_text}

**אירועים אקוסטיים ואירועי בכי שאותרו (חובה לכלול בדוח!)**:
{events_text}

**סיכומי השלבים שנאספו לאורך היום**:
{blocks_text}

אנא סנתז דוח פדגוגי סופי מלא במבנה ה-JSON הנדרש. ודא כי כל אירוע בכי מופיע בניתוח הרגשי, בציר הזמן ובנורות האזהרה!
"""
